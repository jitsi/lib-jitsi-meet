/**
 * Generates a source name.
 *
 * @param {EndpointId} endpointId - Jitsi Endpoint Id.
 * @param {MediaType} mediaType - the media type string.
 * @param {number} trackIdx - Track index (or sender idx? - to be figured out) starting from 0.
 * @returns {SourceName} eg. endpointA-v0
 */
export function getSourceNameForJitsiTrack(endpointId: EndpointId, mediaType: MediaType, trackIdx: number): SourceName {
    const firstLetterOfMediaType = mediaType.substring(0, 1);

    return `${endpointId}-${firstLetterOfMediaType}${trackIdx}`;
}

/**
 * The shape of a source name as generated by {@link getSourceNameForJitsiTrack}: the owner endpoint id (which may
 * itself contain '-'), '-', the media type letter, the track index, and an optional '.<suffix>' that a synthetic
 * (bridge-injected) source carries for its language, eg. 'endpointA-a0.es' or 'endpointA-a0.pt-BR'. The suffix may
 * contain '-' (a BCP-47 region or script subtag), so the media type and index are taken from the segment before
 * the suffix. Neither the endpoint id nor the suffix may contain '.': the single '.' is what marks a translated
 * source ({@link isTranslatedSourceName}), and anchoring both groups on it keeps a suffix that happens to end in
 * '-a1' or '-v12' from being read as the media segment.
 */
const SOURCE_NAME_RE = /^([^.]+)-([av])(\d+)(?:\.([^.]+))?$/;

/**
 * Splits a source name into its parts, or throws if it is not in the format {@link getSourceNameForJitsiTrack}
 * generates.
 *
 * @param {SourceName} sourceName - the source name.
 * @returns {{ endpointId: EndpointId, mediaType: MediaType, trackIdx: number }}
 */
function parseSourceName(sourceName: SourceName): { endpointId: EndpointId; mediaType: MediaType; trackIdx: number; } {
    const match = SOURCE_NAME_RE.exec(sourceName);

    if (!match) {
        throw new Error(`Invalid source name: ${sourceName}`);
    }

    return {
        endpointId: match[1],
        mediaType: match[2] === 'v' ? MediaType.VIDEO : MediaType.AUDIO,
        trackIdx: Number(match[3])
    };
}

/**
 * Extracts MediaType from give source name (must be in the correct format as generated by
 * {@link getSourceNameForJitsiTrack}).
 *
 * @param {SourceName} sourceName - the source name.
 * @returns {MediaType}
 */
export function getMediaTypeFromSourceName(sourceName: SourceName): MediaType {
    return parseSourceName(sourceName).mediaType;
}

/**
 * Extracts the owner endpoint id from a given source name (must be in the correct format as generated by
 * {@link getSourceNameForJitsiTrack}).
 *
 * @param {SourceName} sourceName - the source name, eg. endpointA-v0.
 * @returns {EndpointId}
 */
export function getEndpointIdFromSourceName(sourceName: SourceName): EndpointId {
    return parseSourceName(sourceName).endpointId;
}

/**
 * Extracts source index (zero based) from a given source name (must be in the correct format as generated by
 * {@link getSourceNameForJitsiTrack}).
 *
 * @param {SourceName} sourceName - the source name, eg. endpointA-v0.
 * @returns {number}
 */
export function getSourceIndexFromSourceName(sourceName: SourceName): number {
    return parseSourceName(sourceName).trackIdx;
}

/**
 * Checks whether the given source name belongs to a translated audio source. Translated sources follow the
 * convention {@code <regularSourceName>.<ISO-639-1-language>}, eg. endpointA-a0.en, whereas regular source
 * names never contain a dot.
 *
 * @param {SourceName} sourceName - The source name to check (callers may pass a null/undefined source name).
 * @returns {boolean}
 * @deprecated Name heuristic, kept only as the fallback for bridges that do not signal the source kind. Prefer
 * {@link SignalingLayer#getSyntheticSourceKind}.
 */
export function isTranslatedSourceName(sourceName?: SourceName | null): boolean {
    return typeof sourceName === 'string' && sourceName.includes('.');
}

/** Reserved endpoint-id namespace for bridge-injected voice agents (mirrors the server-side `agent-` prefix). */
export const AGENT_ENDPOINT_ID_PREFIX = 'agent-';

/**
 * Whether an id belongs to a voice agent. Agents are bridge-injected synthetic endpoints in the reserved
 * `agent-` namespace and, unlike real participants, publish no MUC presence. Their source names
 * (`agent-<id>-a0`) inherit the prefix, so this matches both endpoint ids and source names.
 *
 * @param {string} id - An endpoint id or source name (callers may pass null/undefined).
 * @returns {boolean}
 * @deprecated Name heuristic, kept only as the fallback for bridges that do not signal the source kind. Prefer
 * {@link SignalingLayer#getSyntheticSourceKind}.
 */
export function isVoiceAgentEndpointId(id?: EndpointId | SourceName | null): boolean {
    return typeof id === 'string' && id.startsWith(AGENT_ENDPOINT_ID_PREFIX);
}

/**
 * Whether a source is bridge-injected (audio translation or voice agent) and therefore never carried in MUC
 * presence — its media state is signaled out of band, so callers must not expect a presence entry for it.
 *
 * @param {SourceName} sourceName - The source name to check (callers may pass null/undefined).
 * @returns {boolean}
 * @deprecated Name heuristic, kept only as the fallback for bridges that do not signal the source kind. Prefer
 * {@link SignalingLayer#isSyntheticSource}.
 */
export function isSyntheticSourceName(sourceName?: SourceName | null): boolean {
    return isTranslatedSourceName(sourceName) || isVoiceAgentEndpointId(sourceName);
}

/**
 * Whether a value received from the bridge is a known {@link SyntheticSourceKind}.
 *
 * @param {string|null|undefined} kind - The value to check.
 * @returns {boolean}
 */
export function isSyntheticSourceKind(kind?: string | null): kind is SyntheticSourceKind {
    return kind === 'agent' || kind === 'translation';
}

/**
 * An object that carries the info about specific media type advertised by
 * participant in the signaling channel.
 * @typedef {Object} IPeerMediaInfo
 * @property {boolean} muted indicates if the media is currently muted
 * @property {VideoType|undefined} videoType the type of the video if applicable
 */

/**
 * Interface used to expose the information carried over the signaling channel
 * which is not available to the RTC module in the media SDP.
 *
 * @interface SignalingLayer
 */
export default class SignalingLayer extends Listenable {
    /**
     * The kinds of the synthetic sources signaled by the bridge so far, keyed by source name.
     */
    private _syntheticSourceKinds: Map<SourceName, SyntheticSourceKind> = new Map();

    /**
     * Forgets every synthetic source kind, e.g. when the bridge session that signaled them ends.
     *
     * @returns {void}
     */
    clearSyntheticSourceKinds(): void {
        this._syntheticSourceKinds.clear();
    }

    /**
     * Obtains the info about given media advertised in the MUC presence of
     * the participant identified by the given MUC JID.
     * @param {string} owner the MUC jid of the participant for whom
     * {@link PeerMediaInfo} will be obtained.
     * @param {MediaType} mediaType the type of the media for which presence
     * @param {SourceName} sourceName - The name of the source for which the info is to be obtained.
     * info will be obtained.
     * @return {Nullable<IPeerMediaInfo>} presenceInfo an object with media presence
     * info or <tt>null</tt> either if there is no presence available for given
     * JID or if the media type given is invalid.
     *
     * @deprecated This method is to be replaced with getPeerSourceInfo.
     */
    getPeerMediaInfo(
            owner: string, mediaType: MediaType, sourceName: SourceName
    ): Nullable<IPeerMediaInfo> {
        throw new Error('not implemented');
    }

    /**
     * Obtains the info about a source for given name and endpoint ID.
     * @param {EndpointId} owner - The owner's endpoint ID.
     * @param {SourceName} sourceName - The name of the source for which the info is to be obtained.
     * @returns {Optional<ITPCSourceInfo>}
     */
    getPeerSourceInfo(
            owner: EndpointId, sourceName: SourceName
    ): Optional<ISourceInfo> {
        throw new Error('not implemented');
    }

    /**
     * Obtains the endpoint ID for given SSRC.
     * @param {number} ssrc the SSRC number.
     * @return {Nullable<string>} the endpoint ID for given media SSRC.
     */
    getSSRCOwner(ssrc: number): Nullable<string> {
        throw new Error('not implemented');
    }

    /**
     * Obtains the kind of a synthetic (bridge-injected) source as signaled by the bridge.
     *
     * @param {SourceName} sourceName - The source name (callers may pass null/undefined).
     * @returns {Optional<SyntheticSourceKind>} 'agent' or 'translation', or undefined for regular sources and when
     * the bridge did not signal a kind.
     */
    getSyntheticSourceKind(sourceName?: SourceName | null): Optional<SyntheticSourceKind> {
        return sourceName ? this._syntheticSourceKinds.get(sourceName) : undefined;
    }

    /**
     * Obtains the source name for given SSRC.
     * @param {number} ssrc the track's SSRC identifier.
     * @returns {Optional<SourceName>} the track's source name.
     */
    getTrackSourceName(ssrc: number): Optional<SourceName> {
        throw new Error('not implemented');
    }

    /**
     * Whether a source is bridge-injected (audio translation or voice agent) and therefore never carried in MUC
     * presence. A kind signaled by the bridge wins; the source-name heuristics only cover bridges that do not
     * send one.
     *
     * @param {SourceName} sourceName - The source name (callers may pass null/undefined).
     * @returns {boolean}
     */
    isSyntheticSource(sourceName?: SourceName | null): boolean {
        return Boolean(this.getSyntheticSourceKind(sourceName)) || isSyntheticSourceName(sourceName);
    }

    /**
     * Removes the association between a given SSRC and its current owner so that it can re-used when the SSRC gets
     * remapped to another source from a different endpoint.
     * @param {number} ssrc a list of SSRCs.
     */
    removeSSRCOwners(ssrcList: number[]): void {
    }

    /**
     * Forgets the kinds of the given synthetic sources, e.g. when their owner leaves.
     *
     * @param {SourceName[]} sourceNames - The source names.
     * @returns {void}
     */
    removeSyntheticSourceKinds(sourceNames: SourceName[]): void {
        for (const sourceName of sourceNames) {
            this._syntheticSourceKinds.delete(sourceName);
        }
    }

    /**
     * Set an SSRC owner.
     *
     * @param {number} ssrc - An SSRC to be owned.
     * @param {string} endpointId - Owner's ID (MUC nickname).
     * @param {SourceName} sourceName - The related source name.
     * @throws TypeError if <tt>ssrc</tt> is not a number.
     */
    setSSRCOwner(ssrc: number, endpointId: string, sourceName: SourceName): void {
    }

    /**
     * Records the kind of a synthetic source as signaled by the bridge.
     *
     * @param {SourceName} sourceName - The source name.
     * @param {SyntheticSourceKind} kind - The kind.
     * @returns {void}
     */
    setSyntheticSourceKind(sourceName: SourceName, kind: SyntheticSourceKind): void {
        this._syntheticSourceKinds.set(sourceName, kind);
    }

    /**
     * Adjusts muted status of given track.
     *
     * @param {SourceName} sourceName - the name of the track's source.
     * @param {boolean} muted - the new muted status.
     * @returns {boolean}
     */
    setTrackMuteStatus(sourceName: SourceName, muted: boolean) {
    }

    /**
     * Sets track's video type.
     * @param {SourceName} sourceName - the track's source name.
     * @param {VideoType} videoType - the new video type.
     * @returns {boolean}
     */
    setTrackVideoType(sourceName: SourceName, videoType: VideoType) {
    }

    /**
     * Removes the SSRCs associated with a given endpoint from the SSRC owners.
     *
     * @param {string} id endpoint id of the participant leaving the call.
     * @returns {void}
     */
    updateSsrcOwnersOnLeave(id: string): void {
    }
}
